function specialty({
  id,
  name,
  category,
  relatedChecks,
  description,
  ranks,
  prerequisites = {},
  tags = [],
  context,
}) {
  return {
    id,
    name,
    category,
    relatedChecks,
    description,
    maxRank: ranks.length,
    ranks,
    prerequisites,
    tags: [category, ...tags],
    context,
  };
}

function rank(rank, title, effect) {
  return { rank, title, effect };
}

function corePrerequisites(primaryCheck, secondaryCheck = primaryCheck) {
  return {
    2: [{ coreCheck: primaryCheck, min: 15 }],
    3: [{ coreCheck: secondaryCheck, min: 16 }],
    4: [{ coreCheck: primaryCheck, min: 17 }],
  };
}

